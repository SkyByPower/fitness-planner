TRANSLATIONS = {"ru": RU}


def get_locale():
    if not has_request_context():
        return DEFAULT_LANGUAGE
    lang = session.get("lang")
    if lang in LANGUAGES:
        return lang
    return request.accept_languages.best_match(["kk", "ru"]) or DEFAULT_LANGUAGE


def gettext(text, **kwargs):
    translated = TRANSLATIONS.get(get_locale(), {}).get(str(text), str(text))
    return translated.format(**kwargs) if kwargs else translated


class LazyString:
    """Сұраныс кезінде ғана аударылатын жол (формалар мен модельдер үшін)."""

    def __init__(self, text):
        self.text = text

    def __str__(self):
        return gettext(self.text)

    def __html__(self):
        return str(escape(str(self)))

    def __mod__(self, other):
        return str(self) % other

    def __eq__(self, other):
        return str(self) == str(other)

    def __hash__(self):
        return hash(self.text)

    def __len__(self):
        return len(str(self))

    def __repr__(self):
        return f"LazyString({self.text!r})"


def lazy_gettext(text):
    return LazyString(text)
